const north = 84;
const south = -58;
export const mapScale = 2.4;
export const mapWidth = 360 * mapScale;
export const mapHeight = (north - south) * mapScale;

export const project = (longitude: number, latitude: number) => ({
  x: (longitude + 180) * mapScale,
  y: (north - latitude) * mapScale,
});

function inside(longitude: number, latitude: number, ring: [number, number][]) {
  let result = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      yi > latitude !== yj > latitude &&
      longitude < ((xj - xi) * (latitude - yi)) / (yj - yi) + xi
    )
      result = !result;
  }
  return result;
}

export type MapDot = {
  x: number;
  y: number;
  longitude: number;
  latitude: number;
};

export const landDots: MapDot[] = (() => {
  const dots: MapDot[] = [];
  const step = 2.5;
  for (let latitude = north - step / 2; latitude > south; latitude -= step)
    for (let longitude = -180 + step / 2; longitude < 180; longitude += step)
      if (landmasses.some((ring) => inside(longitude, latitude, ring)))
        dots.push({ ...project(longitude, latitude), longitude, latitude });
  return dots;
})();

// Zero-length round-capped segments render as dots in a single path element.
export const dotPath = (dots: MapDot[]) =>
  dots.map(({ x, y }) => `M${x.toFixed(1)} ${y.toFixed(1)}h0`).join('');
